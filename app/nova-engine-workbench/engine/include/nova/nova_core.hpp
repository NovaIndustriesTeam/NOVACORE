#pragma once

#include <cstdint>
#include <optional>
#include <string>
#include <string_view>
#include <vector>

namespace nova {
struct EngineInfo {
    std::string_view name;
    std::string_view version;
    int apiVersion;
};

struct Vec3 {
    float x{0.0F};
    float y{0.0F};
    float z{0.0F};
    friend constexpr bool operator==(const Vec3&, const Vec3&) = default;
};

struct Transform {
    Vec3 position{};
    Vec3 rotationDegrees{};
    Vec3 scale{1.0F, 1.0F, 1.0F};
};

// Procedural surface patterns shared by every renderer. They stay available
// when no image texture is bound, so renders are reproducible without assets.
enum class SurfacePattern {
    None,
    Checker,
    Grid,
};

[[nodiscard]] const char* surfacePatternName(SurfacePattern pattern) noexcept;
[[nodiscard]] bool parseSurfacePattern(std::string_view name, SurfacePattern& pattern) noexcept;

// Primitive meshes generated by the engine. `Primitive` is serialized as a
// string so scenes stay readable and stable across versions.
enum class Primitive {
    Cube,
    Sphere,
    Plane,
    Cylinder,
    Cone,
    Torus,
    Capsule,
    Pyramid,
};

[[nodiscard]] const char* primitiveName(Primitive primitive) noexcept;
[[nodiscard]] bool parsePrimitive(std::string_view name, Primitive& primitive) noexcept;

// Per-entity PBR material. `albedo` is stored in sRGB [0,1] like the editor
// colour picker; renderers convert it once to linear space. `texture` is an
// optional PNG/JPEG path relative to the render asset root; an empty string
// keeps the procedural pattern only.
struct Material {
    Vec3 albedo{0.82F, 0.85F, 0.90F};
    float metallic{0.0F};
    float roughness{0.5F};
    float tiling{4.0F};
    SurfacePattern pattern{SurfacePattern::None};
    bool emissive{false};
    std::string texture{};
    friend constexpr bool operator==(const Material&, const Material&) = default;
};

enum class LightType {
    Directional,
    Point,
    Spot,
};

[[nodiscard]] const char* lightTypeName(LightType type) noexcept;
[[nodiscard]] bool parseLightType(std::string_view name, LightType& type) noexcept;

// Per-entity light. Scenes may contain several lights; the renderers evaluate
// up to eight of them. `spotAngle` is the outer cone angle in degrees and
// `range` is the attenuation radius for point/spot lights.
struct Light {
    LightType type{LightType::Directional};
    Vec3 color{1.0F, 0.94F, 0.84F};
    float intensity{1.0F};
    float range{8.0F};
    float spotAngle{35.0F};
    bool castShadow{true};
    friend constexpr bool operator==(const Light&, const Light&) = default;
};

// Optional gameplay components. They are plain data: the Runtime owns the
// simulation state and mutates the live scene while play mode is active.
struct Rigidbody {
    Vec3 velocity{};
    float mass{1.0F};
    float bounciness{0.25F};
    bool gravity{true};
    friend constexpr bool operator==(const Rigidbody&, const Rigidbody&) = default;
};

struct Controller {
    float speed{4.0F};
    float jumpSpeed{5.0F};
    friend constexpr bool operator==(const Controller&, const Controller&) = default;
};

struct Spinner {
    Vec3 axis{0.0F, 1.0F, 0.0F};
    float degreesPerSecond{45.0F};
    friend constexpr bool operator==(const Spinner&, const Spinner&) = default;
};

struct Collectible {
    float radius{1.0F};
    int value{1};
    friend constexpr bool operator==(const Collectible&, const Collectible&) = default;
};

struct Entity {
    std::string id;
    std::optional<std::string> parentId{};
    std::string name;
    std::string type{"Empty"};
    Transform transform{};
    bool visible{true};
    std::vector<std::string> components{};
    // Optional: older scenes omit it and inherit the type-based default palette.
    std::optional<Material> material{};
    // Mesh primitive. `primitiveExplicit` keeps schema 1-3 scenes on the
    // historical name-based inference until the editor writes schema 4.
    Primitive primitive{Primitive::Cube};
    bool primitiveExplicit{false};
    std::optional<Light> light{};
    std::optional<Rigidbody> rigidbody{};
    std::optional<Controller> controller{};
    std::optional<Spinner> spinner{};
    std::optional<Collectible> collectible{};
};

// Fallback material used when an entity has no explicit material. It reproduces
// the historical type palette so schema 1/2 scenes keep their look.
[[nodiscard]] Material defaultMaterialFor(const Entity& entity) noexcept;
// Explicit primitive, or the historical name/component inference used by
// schema 1-3 documents.
[[nodiscard]] Primitive primitiveFor(const Entity& entity) noexcept;
[[nodiscard]] bool isValidMaterial(const Material& material) noexcept;
[[nodiscard]] bool isValidLight(const Light& light) noexcept;
[[nodiscard]] bool isValidTexturePath(std::string_view path) noexcept;

class Scene {
public:
    [[nodiscard]] std::string createEntity(std::string name, std::string type = "Empty");
    [[nodiscard]] bool insertEntity(Entity entity);
    [[nodiscard]] bool duplicateEntity(const std::string& id, std::optional<std::string> newName = std::nullopt);
    [[nodiscard]] bool renameEntity(const std::string& id, std::string name);
    [[nodiscard]] bool removeEntity(const std::string& id);
    [[nodiscard]] Entity* findEntity(const std::string& id) noexcept;
    [[nodiscard]] const Entity* findEntity(const std::string& id) const noexcept;
    [[nodiscard]] std::vector<Entity>& entities() noexcept;
    [[nodiscard]] const std::vector<Entity>& entities() const noexcept;
    [[nodiscard]] std::size_t visibleEntityCount() const noexcept;
    [[nodiscard]] bool setParent(const std::string& childId, std::optional<std::string> parentId) noexcept;
    [[nodiscard]] std::optional<Transform> worldTransform(const std::string& id) const noexcept;

    [[nodiscard]] const std::string& name() const noexcept;
    void setName(std::string name);
    [[nodiscard]] const std::optional<std::string>& updatedAt() const noexcept;
    void setUpdatedAt(std::optional<std::string> value);
    void clear() noexcept;
private:
    std::string name_{"Nouvelle scène"};
    std::optional<std::string> updatedAt_{};
    std::vector<Entity> entities_;
    std::uint64_t nextId_{1};
};

struct FrameStats {
    std::uint64_t frameNumber{};
    double deltaSeconds{};
    std::size_t visibleEntities{};
};

// Input for one play-mode step. `moveForward`/`moveRight` are in [-1, 1] and
// `lookYaw`/`lookPitch` are mouse deltas in degrees for the current frame.
struct PlayInput {
    float moveForward{0.0F};
    float moveRight{0.0F};
    float lookYaw{0.0F};
    float lookPitch{0.0F};
    bool jump{false};
};

struct PlayStats {
    bool active{false};
    int score{0};
    int collected{0};
    int totalCollectibles{0};
    int players{0};
    bool playerGrounded{false};
    Vec3 playerPosition{};
};

// Headless runtime. `tick` advances frame statistics; `play` runs the
// deterministic gameplay simulation (character controller, gravity, spinners,
// collectibles) on a live scene. It is intentionally dependency free so the
// same rules can be tested without a window or a GPU.
class Runtime {
public:
    void initialize() noexcept;
    void shutdown() noexcept;
    [[nodiscard]] bool initialized() const noexcept;
    [[nodiscard]] FrameStats tick(double deltaSeconds, const Scene& scene) noexcept;
    [[nodiscard]] const FrameStats& stats() const noexcept;

    [[nodiscard]] bool startPlay(const Scene& scene);
    void stopPlay() noexcept;
    [[nodiscard]] bool playing() const noexcept;
    void play(Scene& scene, const PlayInput& input, double deltaSeconds);
    [[nodiscard]] const PlayStats& playStats() const noexcept;
private:
    struct BodyState {
        std::string id;
        float velocityY{0.0F};
        bool grounded{false};
    };
    [[nodiscard]] BodyState* body(const std::string& id) noexcept;
    bool initialized_{false};
    FrameStats stats_{};
    PlayStats playStats_{};
    std::vector<BodyState> bodies_{};
    float yaw_{0.0F};
    float pitch_{0.0F};
    float playerEyeHeight_{1.6F};
    bool jumpLatch_{false};
};

[[nodiscard]] EngineInfo info() noexcept;
[[nodiscard]] bool isSupportedApiVersion(int version) noexcept;
[[nodiscard]] bool isValidTransform(const Transform& transform) noexcept;
[[nodiscard]] Transform combineTransforms(const Transform& parent, const Transform& local) noexcept;

// Scene document contract shared with the Workbench (schemaVersion 4 JSON).
[[nodiscard]] bool validateScene(const Scene& scene, std::string& error);
[[nodiscard]] std::string sceneToJson(const Scene& scene);
[[nodiscard]] bool sceneFromJson(std::string_view json, Scene& scene, std::string& error);
}  // namespace nova
